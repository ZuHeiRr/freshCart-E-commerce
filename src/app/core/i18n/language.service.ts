import { DOCUMENT, isPlatformBrowser } from '@angular/common';
import { inject, Injectable, PLATFORM_ID, signal } from '@angular/core';

export type AppLanguage = 'en' | 'ar';

@Injectable({ providedIn: 'root' })
export class LanguageService {
  private readonly platformId = inject(PLATFORM_ID);
  private readonly document = inject(DOCUMENT);

  readonly language = signal<AppLanguage>('en');

  constructor() {
    if (isPlatformBrowser(this.platformId)) {
      const savedLanguage = localStorage.getItem('freshcart-language');
      if (savedLanguage === 'ar' || savedLanguage === 'en') {
        this.language.set(savedLanguage);
      }
      this.applyLanguage(this.language());
    }
  }

  setLanguage(language: AppLanguage): void {
    this.language.set(language);
    if (isPlatformBrowser(this.platformId)) {
      localStorage.setItem('freshcart-language', language);
      this.applyLanguage(language);
    }
  }

  toggleLanguage(): void {
    this.setLanguage(this.language() === 'en' ? 'ar' : 'en');
  }

  translate(value: string | null | undefined): string {
    if (!value || this.language() === 'en') return value ?? '';
    return translations[value] ?? value;
  }

  private applyLanguage(language: AppLanguage): void {
    this.document.documentElement.lang = language;
    this.document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  }
}

